"""Write the Bounty Board part of the mod from bounty_data.json (build_data.py).

Usage: python3 gen_mod.py WORKDIR MODDIR
  MODDIR/db/quest_db.yml                          the 150-kill quests (always loaded:
                                                  turning the boards off keeps progress)
  MODDIR/npc/when/bounty_boards/bounty_boards.txt the boards
  MODDIR/System/OngoingQuestInfoList.lub          quest text, for clients without iRO's table
"""
import sys, os, json, re

W, M = sys.argv[1], sys.argv[2]
d = json.load(open(os.path.join(W, 'bounty_data.json')))
quests = {q['id']: q for q in d['quests']}

# Where a board would stand on (or next to) an NPC the server already has, it moves.
MOVE = {('comodo', 104, 136): (105, 136), ('comodo', 106, 136): (107, 136), ('comodo', 108, 136): (109, 136)}
SHORT = {'prontera': 'prt', 'izlude': 'izl', 'geffen': 'gef', 'payon': 'pay', 'alberta': 'alb', 'morocc': 'moc',
         'aldebaran': 'ald', 'xmas': 'xms', 'comodo': 'cmd', 'umbala': 'umb', 'niflheim': 'nif', 'malangdo': 'mal',
         'lasagna': 'las', 'yuno': 'yun', 'lighthalzen': 'lhz', 'einbroch': 'ein', 'hugel': 'hug', 'rachel': 'rac',
         'veins': 'vei', 'verus04': 'ver', 'manuk': 'man', 'dicastes01': 'dic', 'splendide': 'spl', 'mora': 'mor',
         'ecl_in01': 'ecl', 'pay_d03_i': 'ilm', 'gef_d01_i': 'ilv', 'ice_d03_i': 'ilf'}
TOWN = {'prontera': 'Prontera', 'izlude': 'Izlude', 'geffen': 'Geffen', 'payon': 'Payon', 'alberta': 'Alberta',
        'morocc': 'Morroc', 'aldebaran': 'Al De Baran', 'xmas': 'Lutie', 'comodo': 'Comodo', 'umbala': 'Umbala',
        'niflheim': 'Niflheim', 'malangdo': 'Malangdo', 'lasagna': 'Lasagna', 'yuno': 'Juno', 'lighthalzen': 'Lighthalzen',
        'einbroch': 'Einbroch', 'hugel': 'Hugel', 'rachel': 'Rachel', 'veins': 'Veins', 'verus04': 'Verus',
        'manuk': 'Manuk', 'dicastes01': 'El Dicastes', 'splendide': 'Splendide', 'mora': 'Mora', 'ecl_in01': 'Eclage',
        'pay_d03_i': 'the Illusion of Moonlight', 'gef_d01_i': 'the Illusion of Vampire', 'ice_d03_i': 'the Illusion of Frozen'}


def ascii(s):
    s = s.replace('’', "'").replace('‘', "'").replace('“', '"').replace('”', '"')
    return s.encode('ascii', 'replace').decode()


# ---- db/quest_db.yml ---------------------------------------------------------
os.makedirs(os.path.join(M, 'db'), exist_ok=True)
y = ['# iRO Quests: quest log entries. Ids are the iRO client\'s own, so its quest',
     '# window already has their text (System/OngoingQuestInfoList.lub repeats it for',
     '# other clients). None of these ids is in rAthena\'s quest_db.',
     '#',
     '# Bounty Boards (62560-63748): hunt 150 of one monster.',
     'Header:', '  Type: QUEST_DB', '  Version: 3', '', 'Body:']
for qid in sorted(quests):
    q = quests[qid]
    y += ['  - Id: %d' % qid, '    Title: "%s"' % ascii(q['title']).replace('"', "'"),
          '    Targets:', '      - Mob: %s' % q['aegis'], '        Count: 150']
open(os.path.join(M, 'db', 'quest_db.yml'), 'w').write('\n'.join(y) + '\n')

# ---- System/OngoingQuestInfoList.lub ----------------------------------------
os.makedirs(os.path.join(M, 'System'), exist_ok=True)
L = ['-- iRO Quests: the text of this mod\'s quests, as the iRO client has it, for',
     '-- clients whose own table lacks them. ASCII only (the client reads it in its',
     '-- own codepage).', 'QuestInfoList = {']
for qid in sorted(quests):
    q = quests[qid]
    desc = ascii(q['desc']).replace('\\', '\\\\').replace('"', '\\"')
    L += ['\t[%d] = {' % qid, '\t\tTitle = "%s",' % ascii(q['title']).replace('"', '\\"'),
          '\t\tSummary = "Hunt 150 %s",' % ascii(q['name']).replace('"', '\\"'),
          '\t\tIconName = "ico_nq.bmp",', '\t\tDescription = { "%s" },' % desc, '\t},']
L.append('}')
open(os.path.join(M, 'System', 'OngoingQuestInfoList.lub'), 'w').write('\n'.join(L) + '\n')

# ---- npc/when/bounty_boards/bounty_boards.txt --------------------------------
S = []
S.append(r'''//===== Ragnarok Offline mod: iRO Quests =====================
//= Bounty Boards
//===== Description: =========================================
//= iRO's Bounty Boards: repeatable hunts of 150 of one monster,
//= posted on boards by level range in most towns, usually next
//= to the tool shop. Take as many as you like; party kills count.
//= Bring the finished hunt back to the board that posted it:
//=   Base EXP = the monster's Base EXP x 150
//=   Job EXP  = the monster's Job EXP x 150
//=   Zeny     = the monster's level x 100
//=   every 4th bounty turned in also pays 1 Eden Merit Badge.
//= The EXP goes through the server's quest EXP rate and its
//= level-up rules, as any quest reward does.
//=
//= Boards and their positions are the iRO client's (navi_npc),
//= the bounties its quest table (62560-63748), the rules
//= iROWiki's "Bounty Board Quests". Generated by
//= tools/bounty/gen_mod.py; edit the generator, not this file.
//============================================================

// getarg(0): town, 1/2: level range, 3: "quest:monster:name,..."
function	script	F_IQ_Bounty	{
	.@town$ = getarg(0);
	.@lo = getarg(1);
	.@hi = getarg(2);
	explode(.@row$, getarg(3), ",");
	.@n = getarraysize(.@row$);
	for (.@i = 0; .@i < .@n; .@i++) {
		explode(.@f$, .@row$[.@i], ":");
		.@q[.@i] = atoi(.@f$[0]);
		.@m[.@i] = atoi(.@f$[1]);
		.@name$[.@i] = .@f$[2];
	}
	mes "[Bounty Board]";
	mes "^0000CCWANTED^000000";
	mes "Hunters needed for the monsters";
	mes "troubling " + .@town$ + ".";
	mes "Recommended level: " + .@lo + " ~ " + .@hi + ".";
	next;
	while (1) {
		.@done = 0;
		for (.@i = 0; .@i < .@n; .@i++)
			if (checkquest(.@q[.@i], HUNTING) == 2)
				.@done++;
		clear;
		mes "[Bounty Board]";
		mes "What will you do?";
		switch (select("Read the bounties", (.@done ? "^0000CCTurn in finished bounties (" + .@done + ")^000000" : ""), "Tear up a bounty I took", "How do bounties work?", "Walk away")) {
		case 1:
			clear;
			mes "[Bounty Board]";
			mes "Which notice will you read?";
			.@menu$ = "";
			for (.@i = 0; .@i < .@n; .@i++) {
				.@s = checkquest(.@q[.@i], HUNTING);
				.@menu$ += .@name$[.@i] + " (Lv " + getmonsterinfo(.@m[.@i], MOB_LV) + ")" + (.@s == 2 ? " ^0000CC[Done]^000000" : (.@s >= 0 ? " ^777777[Taken]^000000" : "")) + ":";
			}
			.@c = select(.@menu$ + "Back") - 1;
			if (.@c == .@n)
				continue;
			.@qid = .@q[.@c];
			.@mob = .@m[.@c];
			clear;
			mes "[Bounty Board]";
			mes "^0000CCWANTED: " + .@name$[.@c] + "^000000";
			mes "Hunt ^FF0000150^000000 of them and return";
			mes "to this board for the reward:";
			mes " - " + callfunc("F_InsertComma", getmonsterinfo(.@mob, MOB_BASEEXP) * 150) + " Base EXP";
			mes " - " + callfunc("F_InsertComma", getmonsterinfo(.@mob, MOB_JOBEXP) * 150) + " Job EXP";
			mes " - " + callfunc("F_InsertComma", getmonsterinfo(.@mob, MOB_LV) * 100) + " Zeny";
			.@s = checkquest(.@qid, HUNTING);
			if (.@s == 2) {
				mes "You have finished this one.";
				mes "Turn it in from the board's menu.";
				break;
			}
			if (.@s >= 0) {
				mes "You are already on this hunt.";
				mes "Your quest log keeps the count.";
				break;
			}
			if (BaseLevel < .@lo || BaseLevel > .@hi) {
				mes "^777777This board posts bounties for";
				mes "adventurers of level " + .@lo + " ~ " + .@hi + ".^000000";
				break;
			}
			next;
			if (select("Take the bounty:Leave it") == 2) {
				mes "[Bounty Board]";
				mes "The notice flutters in the wind.";
				break;
			}
			if (checkquest(.@qid) == 2)
				erasequest .@qid;
			setquest .@qid;
			mes "[Bounty Board]";
			mes "You tear off a copy of the notice.";
			mes "Hunt 150 " + .@name$[.@c] + " and come back.";
			break;
		case 2:
			clear;
			mes "[Bounty Board]";
			for (.@i = 0; .@i < .@n; .@i++) {
				if (checkquest(.@q[.@i], HUNTING) != 2)
					continue;
				.@mob = .@m[.@i];
				erasequest .@q[.@i];
				getexp getmonsterinfo(.@mob, MOB_BASEEXP) * 150, getmonsterinfo(.@mob, MOB_JOBEXP) * 150;
				Zeny += getmonsterinfo(.@mob, MOB_LV) * 100;
				mes "Bounty paid: ^0000CC" + .@name$[.@i] + "^000000.";
				iq_bounty_count++;
				if (iq_bounty_count % 4 == 0) {
					getitem "Eden_Merit_Badge", 1;
					mes "That makes four more bounties:";
					mes "an ^0000CCEden Merit Badge^000000 as well.";
				}
			}
			break;
		case 3:
			clear;
			.@menu$ = "";
			.@k = 0;
			for (.@i = 0; .@i < .@n; .@i++) {
				if (checkquest(.@q[.@i]) < 0 || checkquest(.@q[.@i]) == 2)
					continue;
				.@pick[.@k] = .@i;
				.@k++;
				.@menu$ += .@name$[.@i] + ":";
			}
			mes "[Bounty Board]";
			if (!.@k) {
				mes "You have no bounty from this board.";
				break;
			}
			mes "Which bounty will you give up?";
			mes "^777777Its kill count is lost.^000000";
			next;
			.@c = select(.@menu$ + "None") - 1;
			if (.@c == .@k)
				continue;
			erasequest .@q[.@pick[.@c]];
			mes "[Bounty Board]";
			mes "You tear up the " + .@name$[.@pick[.@c]] + " bounty.";
			break;
		case 4:
			clear;
			mes "[Bounty Board]";
			mes "Each bounty asks for ^FF0000150^000000 of one";
			mes "monster. Take as many as you like:";
			mes "your quest log (Alt+U) counts them.";
			mes "Kills by your party members nearby,";
			mes "your homunculus or mercenary count too.";
			next;
			mes "[Bounty Board]";
			mes "Bring finished bounties back to the";
			mes "board that posted them. You are paid";
			mes "the monster's EXP 150 times over,";
			mes "and 100 zeny per monster level.";
			mes "Every 4th bounty turned in adds an";
			mes "^0000CCEden Merit Badge^000000.";
			break;
		case 5:
			close;
		}
		next;
	}
}
''')

for b in sorted(d['boards'], key=lambda b: (b['map'], b['lo'])):
    x, y = MOVE.get((b['map'], b['x'], b['y']), (b['x'], b['y']))
    qs = [quests[i] for i in sorted(b['quests'], key=lambda i: (quests[i]['lv'], i))]
    data = ','.join('%d:%d:%s' % (q['id'], q['mob'], ascii(q['name']).replace(':', ' ').replace(',', ' ')) for q in qs)
    cond = ' || '.join('checkquest(%d,HUNTING) == 2' % q['id'] for q in qs)
    tag = '%s%d' % (SHORT[b['map']], b['lo'])
    S.append('%s,%d,%d,4\tscript\tBounty Board %d-%d#iq_%s\t837,{' % (b['map'], x, y, b['lo'], b['hi'], tag))
    S.append('\tcallfunc "F_IQ_Bounty", "%s", %d, %d, "%s";' % (TOWN[b['map']], b['lo'], b['hi'], data))
    S.append('\tend;')
    S.append('OnInit:')
    S.append('\tquestinfo QTYPE_QUEST2, QMARK_YELLOW, "%s";' % cond)
    S.append('\tend;')
    S.append('}')
    S.append('')
out = os.path.join(M, 'npc', 'when', 'bounty_boards')
os.makedirs(out, exist_ok=True)
open(os.path.join(out, 'bounty_boards.txt'), 'w').write('\n'.join(S))
print('quests', len(quests), 'boards', len(d['boards']))
