"""Gramps' weekly turn-ins (iRO): build the monster pool and write the mod files.

Usage: python3 gen_gramps.py WORKDIR MODDIR
  WORKDIR: quests_client.json, mobs_small.json, iro_mob_names.json, live2/npc (the live server's npc tree)
Writes:
  MODDIR/db/when/gramps_turn_ins/quest_db.yml       one hunt per monster (iRO's quest ids) + 6 timers
  MODDIR/npc/when/gramps_turn_ins/gramps_pool.txt   the pool, as data for Gramps

Pool: every client quest whose text sends the hunt back to Gramps, its monster resolved to the
server's mob_db and kept only if the server spawns it somewhere; the tier comes from the monster's
level (iROWiki: Low 70-100, Mid 101-125, High 126-150). The order is shuffled once (fixed seed) so
the weekly rotation mixes regions; Gramps walks through it two monsters a week per tier.
"""
import sys, os, re, json, random, collections

W, M = sys.argv[1], sys.argv[2]
raw = json.load(open(os.path.join(W, 'quests_client.json')))['QuestInfoList']
mobs = json.load(open(os.path.join(W, 'mobs_small.json')))
byid = {v['id']: a for a, v in mobs.items()}
iro = {k.lower(): v for k, v in json.load(open(os.path.join(W, 'iro_mob_names.json'))).items()}
srv = collections.defaultdict(list)
for a, v in mobs.items():
    if v['name']:
        srv[v['name'].lower()].append(v['id'])

# Spawn lines on the live server: monster id -> {map: count}
spawn = collections.defaultdict(collections.Counter)
for dp, dn, fn in os.walk(os.path.join(W, 'live2', 'npc')):
    if '/pre-re' in dp or '/test' in dp:
        continue
    for f in fn:
        if not f.endswith('.txt'):
            continue
        for line in open(os.path.join(dp, f), encoding='latin-1'):
            m = re.match(r'^([a-z][\w-]*)(?:,\d+,\d+(?:,\d+,\d+)?)?\t(?:boss_)?monster\t[^\t]*\t(\d+),(\d+)', line)
            if m and not m.group(1).startswith(('1@', '2@', '3@')):
                spawn[int(m.group(2))][m.group(1)] += int(m.group(3))

ALIAS = {'poison toad': [1402], 'blue acidus': [1716], 'gold acidus': [1713], 'egnigem cenia': [1652],
         'seyren-windsor': [1634], 'cecil and eremes': [1638, 1635], 'kathryne and seyren': [1639, 1634],
         'margaretha and howard': [1637, 1636], 'ground petite': [1155], 'removal': [1682], 'hell poodle': [1866],
         'freezer': [1319], 'incarnation of morroc': [1918, 1919], 'dark priest': [1198], 'green lichtern': [2370],
         'red lichtern': [2369], 'blue lichtern': [2367], 'dr815': [3252], 'gc109': [3251], 'neraid': [1255],
         'holden': [1628], 'elder': [1377]}
SKIP = re.compile(r'Timer|VIP|Ferus Faire|Mineral Hunt|Obsidian Hunt')


def resolve(name):
    n = name.strip().lower()
    if n in ALIAS:
        return ALIAS[n]
    c = [i for i in iro.get(n, []) if i in byid]
    if len(c) == 1:
        return c
    c = [i for i in srv.get(n, []) if not re.match(r'(G_|MD_|A_|T_|EVENT_|MIN_|ABI_|CP_|BIO_|W_|E_|C\d_|M_|J_|META_|ECO_|VR_|ILL_)', byid[i])]
    c = [i for i in c if spawn.get(i)] or c
    return c if len(c) == 1 else None


pool, skipped = [], []
for k in sorted(raw, key=int):
    v = raw[k]
    d = v.get('Description') or {}
    d = ' '.join(map(str, d.values())) if isinstance(d, dict) else str(d)
    if 'Gramps' not in d or SKIP.search(v['Title']) or not re.search(r'[Hh]unt', d):
        continue
    name = re.sub(r'\s*(Hunting|Huntin|Hunt Hunt|Hunt)$', '', v['Title'].strip())
    ids = resolve(name)
    if not ids or not all(spawn.get(i) for i in ids):
        skipped.append((int(k), name, 'no monster' if not ids else 'not spawned'))
        continue
    lv = max(mobs[byid[i]]['lv'] for i in ids)
    tier = 1 if lv <= 100 else 2 if lv <= 125 else 3 if lv <= 160 else 0
    if lv < 60 or not tier:
        skipped.append((int(k), name, 'level %d outside the tiers' % lv)); continue
    best = spawn[ids[0]].most_common(1)[0][0]
    pool.append(dict(q=int(k), name=name, ids=ids, lv=lv, tier=tier, map=best))
# one quest per monster set
seen, uniq = set(), []
for p in pool:
    key = tuple(p['ids'])
    if key in seen:
        skipped.append((p['q'], p['name'], 'duplicate of an earlier quest')); continue
    seen.add(key); uniq.append(p)
pool = uniq
random.Random(20261021).shuffle(pool)

TIMERS = [(60444, 60448), (60449, 60450), (60486, 60487)]   # iRO's "Hunting Timer" entries, per tier and slot
y = ["# iRO Quests: Gramps' weekly turn-ins (iRO quest ids). Generated by tools/gramps/gen_gramps.py.",
     'Header:', '  Type: QUEST_DB', '  Version: 3', '', 'Body:']
for p in sorted(pool, key=lambda p: p['q']):
    y += ['  - Id: %d' % p['q'], '    Title: "%s Hunting"' % p['name'], '    Targets:']
    for i in p['ids']:
        y += ['      - Mob: %s' % byid[i], '        Count: 400']
for t, pair in enumerate(TIMERS, 1):
    for s, qid in enumerate(pair):
        y += ['  - Id: %d' % qid, '    Title: "Hunting Timer %d"' % (2 * t - 1 + s), '    TimeLimit: +16h']
dbdir = os.path.join(M, 'db', 'when', 'gramps_turn_ins'); os.makedirs(dbdir, exist_ok=True)
open(os.path.join(dbdir, 'quest_db.yml'), 'w').write('\n'.join(y) + '\n')

S = ["//===== Ragnarok Offline mod: iRO Quests =====================",
     "//= Gramps' weekly turn-ins: the monster pool (generated by",
     "//= tools/gramps/gen_gramps.py; edit the generator).",
     "//= Row: quest id, monster 1, monster 2 (0 = none), map to warp to, name.",
     "//============================================================",
     "-\tscript\tF_IQ_GrampsPool\t-1,{", "\tend;", "OnInit:"]
for t in (1, 2, 3):
    rows = [p for p in pool if p['tier'] == t]
    S.append('\t// Tier %d: %d monsters' % (t, len(rows)))
    S.append('\tsetarray $@iqg%d_q[0], %s;' % (t, ', '.join(str(p['q']) for p in rows)))
    S.append('\tsetarray $@iqg%d_m1[0], %s;' % (t, ', '.join(str(p['ids'][0]) for p in rows)))
    S.append('\tsetarray $@iqg%d_m2[0], %s;' % (t, ', '.join(str(p['ids'][1] if len(p['ids']) > 1 else 0) for p in rows)))
    S.append('\tsetarray $@iqg%d_map$[0], %s;' % (t, ', '.join('"%s"' % p['map'] for p in rows)))
    S.append('\tsetarray $@iqg%d_name$[0], %s;' % (t, ', '.join('"%s"' % p['name'] for p in rows)))
S += ['\tend;', '}', '']
npcdir = os.path.join(M, 'npc', 'when', 'gramps_turn_ins'); os.makedirs(npcdir, exist_ok=True)
open(os.path.join(npcdir, 'gramps_pool.txt'), 'w').write('\n'.join(S))
c = collections.Counter(p['tier'] for p in pool)
print('pool', len(pool), dict(c), 'skipped', len(skipped))
for s in skipped:
    print('  skip', s)
